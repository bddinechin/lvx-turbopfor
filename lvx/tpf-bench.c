// INTEGER BIT-PACKING as an LVX-2 benchmark: a fourth benchmark shape for
// lvx-perf, and three translation layers measured through one source tree.
//
// WHY THIS SHAPE. lvx-ssw covers a branch-dominated kernel (striped
// Smith-Waterman, where a data-dependent early exit is 43% of the run) and a
// branch-free throughput kernel (inter-sequence, saturating arithmetic).
// lvx-polybench covers dense FP loop nests. Nothing covered BIT MANIPULATION
// -- shift, mask, delta, OR-accumulate over packed integers -- which is its
// own instruction mix and its own scheduling problem. On 2026-10-16 PolyBench
// showed why that distinction earns its keep: all 240 of its
// kernel-measurements were codegen-identical across a vector-comparison change
// set, because its kernels never reach what that change touched. Coverage of
// shapes beats more kernels of one shape.
//
// WHAT IS TIMED, and why decode. Only the UNPACK call. Packing is hoisted out,
// which is both what a real caller does -- an inverted index or a time-series
// store is written once and read many times -- and what keeps an O(n) encode
// cost out of the figure being tracked. Decompression is the operation these
// codecs exist to make fast.
//
// THREE WIDTHS FROM ONE BINARY, which is the point of the design. A SIMD build
// of the library exports the scalar entry point alongside the vector ones, so
// bitnunpack32, bitnunpack128v32 and bitnunpack256v32 can all be called in one
// process, on one dataset, in one run. Nothing differs between the rows but
// the entry point -- no separate build, no separate data, no separate ISS
// invocation to drift. That held-constant structure is what made lvx-ssw's
// inter vs inter-gather comparison mean something, and the same applies here.
//
// The three layers each row exercises:
//
//   scalar     plain C. No SIMDe at all. GCC's auto-vectorizer decides what
//              to do with shift/mask/or loops -- and it does a lot: 2145 SIMD
//              instructions in the object. This row is NOT a null baseline.
//   128v32     the library's hand-written SSE path, through SIMDe's 128-bit
//              lowering onto native LVX vectors.
//   256v32     the library's hand-written AVX2 path, through SIMDe's 256-bit
//              lowering onto a 128-bit machine. LVX-2 has no 256-bit
//              datapath, so this measures the emulation layer.
//
// CORRECTNESS IS A ROUND TRIP, which is a stronger oracle than anything else
// in lvx-perf and needs no committed reference values. unpack(pack(x)) must
// equal x, element for element, for every width. lvx-ssw needed a native
// oracle generated by make-reference.sh and a committed checksum file; this
// needs neither, because the codec's own inverse is the check. A width whose
// round trip fails prints MISMATCH and no cycle count: on this target a
// miscompile reads as a speed-up, so an ungated number is worse than none.
//
// THE DATA IS GENERATED, NOT BAKED, and deliberately so. These codecs are for
// sorted integer sequences -- docid lists, timestamps -- where the delta
// distribution decides the bit width and therefore the work. A deterministic
// LCG gives a reproducible sequence with a controllable gap distribution in a
// few lines, where baking 65536 integers would add a 256 KB header for no
// extra fidelity. The generator is documented below so a number here is
// re-derivable from the source alone.
#include <stdint.h>
#include <stddef.h>

// Freestanding output and cycle reading, written for this file rather than
// shared with lvx-ssw. That is a LICENSING constraint, not duplication for its
// own sake: lvx-ssw's equivalent carries the Apache-2.0 WITH LLVM-exception
// header, and Apache-2.0's patent and indemnification terms are additional
// restrictions under GPLv2, so Apache-2.0 code does not combine into a GPLv2
// work. (Apache-2.0 into GPLv3 is fine; GPLv2 is the awkward one.) Nothing is
// copied across the boundary in either direction.
//
// There is no printf: this runs bare metal under gem5 over the crt.S in
// lvx-csw's validation/lib, which provides write(2) and exit(2) and nothing
// else, so every number is formatted by hand.
#if defined(__lvx__)
extern long sys_write (int fd, const void *buf, unsigned long n);
static void emit (const char *b, unsigned long n) { sys_write (1, b, n); }
static inline unsigned long long cyc (void)
{
	unsigned long long r;
	__asm__ __volatile__ ("get %0 = $frcc\n\t;;" : "=r"(r) : : "memory");
	return r;
}
#else
#include <unistd.h>
#include <x86intrin.h>
static void emit (const char *b, unsigned long n) { (void)!write (1, b, n); }
/* RDTSC so the native reference is in the same unit as the target's. It ticks
   at a fixed reference rate rather than the core's actual frequency, so this
   is cycles-at-base-clock -- fine for an order of magnitude, not for three
   digits. */
static inline unsigned long long cyc (void) { return __rdtsc (); }
#endif

static unsigned slen (const char *s) { unsigned n = 0; while (s[n]) n++; return n; }
static void puts_ (const char *s) { emit (s, slen (s)); }

static void putnum (const char *tag, long long v)
{
	char b[32]; unsigned i = sizeof b;
	int neg = v < 0;
	unsigned long long u = neg ? (unsigned long long)(-v) : (unsigned long long) v;
	if (!u) b[--i] = '0';
	while (u) { b[--i] = (char)('0' + u % 10); u /= 10; }
	if (neg) b[--i] = '-';
	puts_ (tag);
	emit (&b[i], sizeof b - i);
}

/* v scaled by 1000, printed as d.ddd -- cycles/int is near 1, so an integer
   would quantise the measurement away. */
static void putfix (const char *tag, unsigned long long v1000)
{
	char b[32]; unsigned i = sizeof b;
	for (int d = 0; d < 3; d++) { b[--i] = (char)('0' + v1000 % 10); v1000 /= 10; }
	b[--i] = '.';
	if (!v1000) b[--i] = '0';
	while (v1000) { b[--i] = (char)('0' + v1000 % 10); v1000 /= 10; }
	puts_ (tag);
	emit (&b[i], sizeof b - i);
}

#define N      (1u << 16)          /* 65536 integers: 256 KB in, 256 KB out */
#define PADPKD (N * 5u + 1024u)    /* worst case is larger than the input */

/* Two codecs, because they land in different bit-width regimes and therefore
 * run different unrolled paths:
 *
 *   bitnpack   packs the values as they are. On a monotonic sequence those are
 *              magnitudes up to ~134M, so ~26 bits per integer -- near the
 *              widest, least compressible case.
 *   bitndpack  packs the DELTAS, which is what the library exists for on
 *              sorted data: docid lists and timestamps. ~12 bits per integer
 *              here, so a different set of unrolled width-specific routines.
 *
 * Measuring only one would report a single bit width as if it were the codec. */
/* WHICH ENTRY POINTS EXIST IS PER-CONFIG, and not the way one might assume.
 * bitunpack.c is an #ifndef __AVX2__ / #ifdef __AVX2__ / #elif __SSE2__ chain,
 * so exactly one branch compiles and __AVX2__ EXCLUDES the plain block.
 * Verified against the objects' symbol tables rather than inferred:
 *
 *   scalar config   bitnunpack32, bitndunpack32
 *   sse config      those PLUS bitnunpack128v32, bitndunpack128v32
 *   avx2 config     those PLUS bitnunpack256v32, bitndunpack256v32
 *
 * The scalar entry points are present in every config, but in the avx2 one
 * that is only because the runner compiles each codec file a SECOND time
 * without __AVX2__ and links both objects -- upstream's own scheme, and
 * necessary because the AVX2 routines call into the plain block that defining
 * __AVX2__ removes. See lvx/run-tpf.sh.
 *
 * That makes the scalar row the methodology control across ALL THREE configs:
 * it is the same source through the same compiler every time, so it must come
 * out identical. If it does not, the builds differ in some way nobody
 * intended. 128-bit and 256-bit never coexist, so each is compared against
 * that shared scalar row rather than directly against each other. */
size_t bitnpack32    (uint32_t *in, size_t n, unsigned char *out);
size_t bitnunpack32  (unsigned char *in, size_t n, uint32_t *out);
size_t bitndpack32   (uint32_t *in, size_t n, unsigned char *out);
size_t bitndunpack32 (unsigned char *in, size_t n, uint32_t *out);
#if (defined(__SSE2__) || defined(__SSSE3__) || defined(__SSE3__)) && !defined(__AVX2__)
size_t bitnpack128v32    (uint32_t *in, size_t n, unsigned char *out);
size_t bitnunpack128v32  (unsigned char *in, size_t n, uint32_t *out);
size_t bitndpack128v32   (uint32_t *in, size_t n, unsigned char *out);
size_t bitndunpack128v32 (unsigned char *in, size_t n, uint32_t *out);
#endif
#if defined(__AVX2__)
size_t bitnpack256v32    (uint32_t *in, size_t n, unsigned char *out);
size_t bitnunpack256v32  (unsigned char *in, size_t n, uint32_t *out);
size_t bitndpack256v32   (uint32_t *in, size_t n, unsigned char *out);
size_t bitndunpack256v32 (unsigned char *in, size_t n, uint32_t *out);
#endif

static uint32_t      src[N];
static uint32_t      dst[N];
static unsigned char pkd[PADPKD];

/* A 64-bit LCG (Knuth's MMIX constants), taken 20 bits at a time for the gap.
 * Monotonically increasing output with gaps in [1, 4096), which is the shape a
 * docid list has and keeps the per-block bit width in the 1..13 range where
 * these codecs do their real work -- a uniform-random uint32 array would pin
 * every block at 32 bits and measure only the widest, least interesting path. */
static void gen (void)
{
	uint64_t s = 88172645463325252ull;
	uint32_t x = 0;
	for (unsigned i = 0; i < N; i++) {
		s = s * 6364136223846793005ull + 1442695040888963407ull;
		x += 1u + (uint32_t) ((s >> 44) & 0xfffu);
		src[i] = x;
	}
}

/* Mixed into a single value so one number stands for the whole array. */
static uint32_t sum32 (const uint32_t *a, unsigned n)
{
	uint32_t h = 2166136261u;
	for (unsigned i = 0; i < n; i++)
		h = (h ^ a[i]) * 16777619u;
	return h;
}

static int ok_roundtrip (void)
{
	for (unsigned i = 0; i < N; i++)
		if (dst[i] != src[i])
			return 0;
	return 1;
}

/* RESULT lines are parsed by harness/run.sh. One per width, self-describing,
 * so adding a width needs no change at the other end. */
static void report (const char *width, unsigned long long cycles, size_t bytes)
{
	puts_ ("RESULT\t"); puts_ (width);
	putnum ("\tcycles ", (long long) cycles);
	putnum ("\tints ", (long long) N);
	putnum ("\tpacked_bytes ", (long long) bytes);
	/* bits per integer x100, the compression ratio these codecs are judged
	   on, and the thing that decides how much work a decode does. */
	putfix ("\tbits_per_int ", (unsigned long long) bytes * 8ull * 1000ull / N);
	putfix ("\tcycles_per_int ", cycles * 1000ull / N);
	putnum ("\tchecksum ", (long long) sum32 (dst, N));
	puts_ ("\n");
}

#define RUN(tag, packfn, unpackfn)                                            \
	do {                                                                  \
		size_t nb = packfn (src, N, pkd);                             \
		for (unsigned i = 0; i < N; i++) dst[i] = 0;                  \
		unpackfn (pkd, N, dst);                                       \
		if (!ok_roundtrip ()) {                                       \
			puts_ ("MISMATCH " tag "\n");                         \
			puts_ ("FAIL: round trip does not reproduce input\n"); \
			return 1;                                             \
		}                                                             \
		for (unsigned i = 0; i < N; i++) dst[i] = 0;                  \
		unsigned long long t0 = cyc ();                               \
		unpackfn (pkd, N, dst);                                       \
		unsigned long long t1 = cyc ();                               \
		if (!ok_roundtrip ()) {                                       \
			puts_ ("MISMATCH " tag " (timed pass)\n");            \
			return 1;                                             \
		}                                                             \
		report (tag, t1 - t0, nb);                                    \
	} while (0)

int main (void)
{
	gen ();
	putnum ("src_checksum ", (long long) sum32 (src, N));
	puts_ ("\n");

	RUN ("bitn/scalar",  bitnpack32,  bitnunpack32);
	RUN ("bitnd/scalar", bitndpack32, bitndunpack32);
#if (defined(__SSE2__) || defined(__SSSE3__) || defined(__SSE3__)) && !defined(__AVX2__)
	RUN ("bitn/128v32",  bitnpack128v32,  bitnunpack128v32);
	RUN ("bitnd/128v32", bitndpack128v32, bitndunpack128v32);
#endif
#if defined(__AVX2__)
	RUN ("bitn/256v32",  bitnpack256v32,  bitnunpack256v32);
	RUN ("bitnd/256v32", bitndpack256v32, bitndunpack256v32);
#endif
	puts_ ("ok\n");
	return 0;
}
